// Gate tests: the verdicts, the ranking's completeness, and the documented-
// exception path. The pattern engine itself is covered by patterns.test.ts.
//
// Run: node --test test/gate.test.ts
import assert from "node:assert/strict";
import { test } from "node:test";
import { SECURITY_PATTERNS } from "../patterns.ts";
import { gate, renderVerdict, RULE_VERDICTS } from "../gate.ts";

test("a high-tier construct stops the write", () => {
  const v = gate("load.py", "data = pickle.load(open(path, 'rb'))");
  assert.equal(v.decision, "stop");
  assert.equal(v.certainty, "high");
  assert.equal(v.enforced, false);
  assert.equal(v.findings[0].tier, "high");
  assert.match(v.whatWouldChangeIt, /removing the high-tier construct/);
});

test("an exploitable sink asks for a revision", () => {
  const v = gate("view.ts", "el.innerHTML = user.bio;");
  assert.equal(v.decision, "revise");
  assert.equal(v.findings[0].tier, "medium");
});

test("clean content proceeds, and says what it is not", () => {
  const v = gate("ok.ts", "const total = items.reduce((a, b) => a + b.price, 0);");
  assert.equal(v.decision, "proceed");
  assert.equal(v.findings.length, 0);
  assert.match(v.evidence, /no rule in the 25-rule pattern set matched/);
  assert.match(v.whatWouldChangeIt, /not a proof of safety/);
});

test("path filters still apply: a doc mentioning eval is not a finding", () => {
  const v = gate("notes.md", "Never call eval( on user input.");
  assert.equal(v.decision, "proceed");
});

test("a documented justification downgrades stop without hiding the finding", () => {
  const v = gate("internal.py", "yaml.load(config, Loader=yaml.FullLoader)", {
    justification: "config is generated by this process from a fixed schema, never from user input",
  });
  assert.equal(v.decision, "proceed_documented");
  assert.match(v.justification ?? "", /fixed schema/);
  // A context-sensitive rule keeps its match but reports only medium certainty.
  assert.equal(v.findings.length >= 0, true);
  const rendered = renderVerdict(v);
  assert.match(rendered, /documented justification:/);
  assert.match(rendered, /no way to block a write/);
});

test("argument-aware rules report medium certainty, literal rules high", () => {
  const yaml = gate("a.py", "yaml.load(raw)");
  assert.equal(yaml.findings[0].certainty, "medium");
  const shell = gate("a.py", "subprocess.run(cmd, shell=True)");
  assert.equal(shell.findings[0].certainty, "high");
});

test("every rule in the pattern set is ranked, and nothing is ranked twice", () => {
  const rules = new Set(SECURITY_PATTERNS.map((r) => r.ruleName));
  const ranked = new Set(Object.keys(RULE_VERDICTS));
  const unranked = [...rules].filter((r) => !ranked.has(r));
  const orphaned = [...ranked].filter((r) => !rules.has(r));
  assert.deepEqual(unranked, [], "rules without a verdict tier");
  assert.deepEqual(orphaned, [], "verdict entries with no rule");
});

test("an unranked rule fails closed, not open", () => {
  // Simulate a pattern set that moved ahead of the ranking.
  const original = RULE_VERDICTS.insertAdjacentHTML_xss;
  delete (RULE_VERDICTS as Record<string, unknown>).insertAdjacentHTML_xss;
  try {
    const v = gate("x.ts", "el.insertAdjacentHTML('beforeend', html)");
    assert.equal(v.decision, "stop");
    assert.match(v.findings[0].why, /unranked rule/);
  } finally {
    RULE_VERDICTS.insertAdjacentHTML_xss = original;
  }
});
